const state = (
  id: string,
  name: string,
  color: number,
  capital: string,
  at: [number, number],
  labelAt: [number, number],
  points: number[][],
  summary: string,
): ChinaHistoricalStateModel => ({
  id,
  name,
  color: palette[color % palette.length],
  capital: { name: capital, at },
  labelAt,
  rings: [[...points, points[0]]],
  summary,
});

